/**
 * volcanic.js - the MEASURED stratospheric aerosol optical depth,
 * live. stratos.js draws the twilight purple light from the
 * background (Kremser-chain) Junge layer with a linear volcScale
 * hook; this module feeds that hook from the real stratosphere:
 * NASA GIBS serves the OMPS Limb Profiler stratospheric aerosol
 * optical depth (NOAA-21) as daily keyless WMTS tiles - the very
 * product Kremser 2016 names as forthcoming (Gorkavyi 2013), the
 * successor of the SAGE/OSIRIS/CALIPSO record the review is
 * built on. The LP retrieval reports aerosol extinction at
 * 675 nm (the product's AMT retrieval-algorithm papers: Loughman
 * 2018 v1 theoretical basis; Taha 2021 v2.1), so the measured
 * column compares against the shipped background chain moved to
 * 675 nm by the same documented Angstrom slope the layer uses:
 *   volcScale = SAOD_675(measured) / stratAOD532() x (532/675)^1.35.
 * The published colormap (v1.3, fetched 2026-08-07) is embedded
 * VERBATIM below and inverted exactly, like snowcover.js does
 * for NDSI: 201 contiguous bins from the 6.00e-3 display floor
 * to the 2.50e-2 top; the floor itself sits at 1.5x the shipped
 * background - the product only paints where the background
 * chain ends, and TODAY's quiet stratosphere reads in the first
 * bins (~1.5x the 1999-2002 minimum), exactly where Kremser
 * places the modern layer (2013 a factor 1.6-2 over the 2002
 * minimum). Unknown cells (no data / below the floor) enter a
 * neighbourhood sample AT the chain background, so an unpainted
 * sky returns volcScale = 1 identically; a week-old tile is
 * honest data (the sulfate e-folding is ~1 year - Kremser after
 * Robock 2000), so the fetch walks back up to 10 days.
 */

