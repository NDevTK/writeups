const LUT = new Map();
for (let i = 0; i < SAOD_RGB.length; i++) {
  const [r, g, b] = SAOD_RGB[i];
  LUT.set((r << 16) | (g << 8) | b, i);
}

// One pixel -> SAOD_675. Returns -1 for unknown (no data /
// unlisted colour), 0 for the below-floor bin, the bin geometric
// mid for interior bins, and the top bin its lower edge (open
// end, stated).
export function saodOfRGBA(r, g, b, a) {
  if (a < 255) return -1;
  const i = LUT.get((r << 16) | (g << 8) | b);
  if (i === undefined) return -1;
  const [, , , lo, hi] = SAOD_RGB[i];
  if (lo === -1) return 0;
  if (hi === -1) return lo;
  return Math.sqrt(lo * hi);
}

// Neighbourhood sample around a global pixel (px, py) at SAOD_Z:
// mean over the (2 half + 1)^2 block with unknown and below-floor
// cells entered AT the chain background - all-quiet returns the
// background exactly. pxAt(ix, iy) -> [r, g, b, a] | null.
export function sampleSaod(pxAt, px, py, half = 16) {
  const bg = chainAOD675();
  let sum = 0;
  let n = 0;
  let painted = 0;
  for (let dy = -half; dy <= half; dy++) {
    for (let dx = -half; dx <= half; dx++) {
      const p = pxAt(px + dx, py + dy);
      if (!p) continue;
      const v = saodOfRGBA(p[0], p[1], p[2], p[3]);
      if (v > 0) {
        sum += v;
        painted++;
      } else {
        sum += bg;
      }
      n++;
    }
  }
  if (!n) return {saod: bg, painted: 0, cells: 0};
  return {saod: sum / n, painted, cells: n};
}

// The layer hook: measured over background, clamped to a sane
// band (the colormap top itself is 6.4x the chain; 8 leaves
// head-room for the open end without letting a bad pixel run
// away). Background and unknown return exactly 1.
export function volcScaleOfSaod(saod675) {
  if (!(saod675 > 0)) return 1;
  return Math.min(Math.max(saod675 / chainAOD675(), 1), 8);
}
