function decode(s) {
  if (typeof Buffer !== 'undefined')
    return new Uint8Array(Buffer.from(s, 'base64'));
  const raw = atob(s);
  const out = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) out[i] = raw.charCodeAt(i);
  return out;
}
