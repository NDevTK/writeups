const LUT = new Map();
for (const e of CREFF_WATER_RGB)
  LUT.set(e[0] + ',' + e[1] + ',' + e[2], {phase: 'water', e});
for (const e of CREFF_ICE_RGB)
  LUT.set(e[0] + ',' + e[1] + ',' + e[2], {phase: 'ice', e});

// One census pixel: an opaque palette colour is a retrieved
// effective radius with its phase (band midpoint, microns);
// anything else is UNSEEN (clear, no retrieval, or the fill).
export function classifyCreff(p) {
  if (!p) return {kind: 'unseen'};
  const [r, g, b, a] = p;
  if (a === 0) return {kind: 'unseen'};
  const hit = LUT.get(r + ',' + g + ',' + b);
  if (!hit) return {kind: 'unseen'};
  return {kind: hit.phase, um: (hit.e[3] + hit.e[4]) / 2};
}

const median = (arr) => {
  if (!arr.length) return null;
  const s = [...arr].sort((a, b) => a - b);
  return s[s.length >> 1];
};

/**
 * Effective-radius statistics over the roam box through the SAME
 * Earth anchoring as the other censuses. Returns {waterUm,
 * iceUm, nWater, nIce}: per-phase medians in microns, null where
 * the satellite saw no such phase - the printed class average
 * stands there.
 */
export function creffStats(sample, anchor, world, n) {
  const water = [];
  const ice = [];
  for (let j = 0; j < n; j++) {
    for (let i = 0; i < n; i++) {
      const x = ((i + 0.5) / n) * world - world / 2;
      const z = ((j + 0.5) / n) * world - world / 2;
      const g = sceneToGeo(x, z, anchor);
      const p = pixelOf(g.lat, g.lon, CREFF_Z);
      const c = classifyCreff(sample(Math.floor(p.px), Math.floor(p.py)));
      if (c.kind === 'water') water.push(c.um);
      else if (c.kind === 'ice') ice.push(c.um);
    }
  }
  return {
    waterUm: median(water),
    iceUm: median(ice),
    nWater: water.length,
    nIce: ice.length
  };
}
