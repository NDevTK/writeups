// ---- the field by sector (the look-here target) ---------------
{
  // a 41 x 41 sea with cloud only in a wedge from 25 to 45 deg of
  // azimuth: of 16 sectors the cloudiest must be the one centred at
  // 33.75 deg (22.5..45), mostly cloudy, its neighbours clear
  const ww = 41;
  const cls = new Uint8Array(ww * ww).fill(CLS.clear);
  const water = new Uint8Array(ww * ww).fill(1);
  for (let j = 0; j < ww; j++)
    for (let i = 0; i < ww; i++) {
      const dx = i + 0.5 - 20.5;
      const dy = j + 0.5 - 20.5;
      const az = ((((Math.atan2(dx, -dy) * 180) / Math.PI) % 360) + 360) % 360;
      if (az >= 25 && az < 45) cls[j * ww + i] = CLS.low;
    }
  const sc = sectorCensus({ww, wh: ww, cls, water}, 20.5, 20.5, 19, 16);
  const sw = sc.sectors[Math.floor((225 / 360) * 16)];
  check(
    'THE SECTOR CENSUS finds the cloudy wedge',
    sc.sectors.length === 16 &&
      sc.cloudiest &&
      near(sc.cloudiest.azDeg, 33.75, 1e-9) &&
      sc.cloudiest.frac > 0.8 &&
      sc.sectors[0].frac < 0.15 &&
      sc.sectors[2].frac === 0 &&
      sw.frac === 0 &&
      sc.sectors.every((s) => s.measured > 0),
    `a cloudy wedge from 25 to 45 deg on a synthetic sea: the cloudiest of 16 sectors is ` +
      `centred at ${sc.cloudiest.azDeg} deg at ${(sc.cloudiest.frac * 100).toFixed(0)}% cloud, ` +
      `its neighbours ${(sc.sectors[0].frac * 100).toFixed(0)}% and 0%, the south-west clear, ` +
      `every sector measured`
  );
}

// ---- the deck field ------------------------------------------
{
  const cx = win.px - i0;
  const cy = win.py - j0;
  const d0 = deckField(P.field, cx, cy, win.halfPx, {metar: null});
  const d1 = deckField(P.field, cx, cy, win.halfPx, {
    metar: {low: 0, mid: 60, high: 0}
  });
  const d2 = deckField(P.field, cx, cy, win.halfPx, {
    metar: {low: 20, mid: 60, high: 0}
  });
  const sum = (d, ch) => {
    let s = 0;
    for (let k = ch; k < d.data.length; k += 4) s += d.data[k];
    return s;
  };
  let border = 0;
  const rm = d0.rm;
  for (let ii = 0; ii < rm; ii++)
    for (const jj of [0, rm - 1])
      border +=
        d0.data[(jj * rm + ii) * 4 + 3] + d0.data[(ii * rm + jj) * 4 + 3];
  const oq = Math.floor(cy) * P.field.ww + Math.floor(cx);
  const ot = ((win.halfPx + 1) * rm + win.halfPx + 1) * 4;
  // mid validity: every sea pixel, and land only where cloud was found
  const waterN = P.field.water.reduce((s, v) => s + v, 0);
  const landCloudN = P.field.cls.filter(
    (c, q) => !P.field.water[q] && (c === CLS.mid || c === CLS.high)
  ).length;
  const landLowN = P.field.cls.filter(
    (c, q) => !P.field.water[q] && c === CLS.low
  ).length;
  check(
    "THE DECK FIELD carries the sea's low cloud to the low deck and the ceilometer's split to the mid",
    rm === 2 * win.halfPx + 3 &&
      border === 0 &&
      near(
        sum(d0, 0),
        0.95 *
          P.field.cls.filter((c, q) => c === CLS.low && P.field.water[q])
            .length,
        1e-3
      ) &&
      near(
        sum(d0, 1),
        0.95 * P.field.cls.filter((c) => c === CLS.mid).length,
        1e-3
      ) &&
      sum(d1, 0) === 0 &&
      near(sum(d1, 1), sum(d0, 1) + sum(d0, 0), 1e-3) &&
      d1.lowToMid &&
      !d2.lowToMid &&
      near(sum(d2, 0), sum(d0, 0), 1e-3) &&
      near(sum(d0, 2), waterN + landCloudN, 1e-6) &&
      near(sum(d1, 2), waterN + landCloudN + landLowN, 1e-6) &&
      d0.data[ot + 3] === (P.field.water[oq] ? 1 : 0),
    `${rm}x${rm} texels with a zero border; the low channel holds ${(sum(d0, 0) / 0.95).toFixed(0)} cloudy ` +
      `sea texels at the 0.95 cap and the mid channel ${(sum(d0, 1) / 0.95).toFixed(0)}; a ceilometer ` +
      `reporting no low layer under a mid one hands them all to the mid deck (${(sum(d1, 1) / 0.95).toFixed(0)}), ` +
      `a low layer keeps them; the mid deck is measured over every sea texel (${waterN}) and over land only where cloud was found ` +
      `(${landCloudN} mid/high${landLowN ? `, +${landLowN} handed over` : ''}) - a land "clear" carves nothing away; ` +
      `the observer's texel is ${d0.data[ot + 3] ? 'measured' : 'unmeasured'} for the low deck ` +
      `(${P.field.water[oq] ? 'water' : 'land'})`
  );
}

