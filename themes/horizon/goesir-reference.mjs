// ---- the height rule ------------------------------------------
{
  const col = [];
  for (let h = 0; h <= 16000; h += 500)
    col.push({
      p: 1013 * Math.exp(-h / 8000),
      hM: h,
      tC: 20 - 0.0065 * h,
      rh: 20
    });
  const trop = coldPoint(col);
  const h1 = heightOfTemperature(col, 20 - 0.0065 * 4321, trop.hM);
  const inv = [
    {p: 1013, hM: 0, tC: 18, rh: 90},
    {p: 960, hM: 450, tC: 15, rh: 95},
    {p: 930, hM: 700, tC: 21, rh: 30},
    {p: 850, hM: 1500, tC: 17, rh: 20},
    {p: 700, hM: 3000, tC: 6, rh: 10},
    {p: 500, hM: 5600, tC: -12, rh: 10},
    {p: 100, hM: 16000, tC: -68, rh: 5}
  ];
  const h680 = heightOfPressure(col, ISCCP_LOW_HPA);
  const h440 = heightOfPressure(col, ISCCP_HIGH_HPA);
  check(
    'THE HEIGHT RULE inverts a monotone column exactly and flags the marine inversion',
    near(h1, 4321, 1e-6) &&
      !lowLevelInversion(col) &&
      lowLevelInversion(inv) &&
      near(((18 - 13) / INVERSION_LAPSE_K_PER_KM) * 1000, 510.204, 1e-3) &&
      near(h680, 8000 * Math.log(1013 / 680), 1e-6) &&
      h440 > h680,
    `a 6.5 K/km column returns ${h1.toFixed(3)} m for its own 4321-m temperature; no inversion ` +
      `there, one in a column warming 15 -> 21 C between 450 and 700 m; a cloud 5 K under the ` +
      `surface in that inversion sits at ${(((18 - 13) / INVERSION_LAPSE_K_PER_KM) * 1000).toFixed(0)} m ` +
      `(ACHA's 9.8 K/km); ISCCP 680 hPa at ${h680.toFixed(0)} m and 440 hPa at ${h440.toFixed(0)} m on the scale-height column`
  );
}

