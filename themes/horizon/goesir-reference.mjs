// ---- the vendored colormap ------------------------------------
{
  let contiguous = true;
  let monotone = true;
  for (let i = 1; i < B13_BINS.length; i++) {
    if (B13_BINS[i].lo !== B13_BINS[i - 1].hi) contiguous = false;
    if (!(B13_BINS[i].tC > B13_BINS[i - 1].tC)) monotone = false;
  }
  const cold = COLD_GREYS;
  const warm = WARM_GREYS;
  check(
    'THE COLORMAP is one contiguous monotone ramp of 238 bins',
    B13_COLORMAP.length === 238 &&
      contiguous &&
      monotone &&
      B13_BINS[0].lo === -92.1 &&
      B13_BINS[237].hi === null,
    `${B13_COLORMAP.length} bins from ${B13_BINS[0].lo} C to +INF, every bin's ` +
      `lower bound the previous bin's upper (contiguous ${contiguous}), readings ` +
      `strictly increasing (${monotone})`
  );
  check(
    "THE THREE GREY FAMILIES are the map's own",
    cold.length === 10 &&
      near(Math.min(...cold.map((e) => e.lo)), -80.1, 1e-9) &&
      near(Math.max(...cold.map((e) => e.hi)), -70.1, 1e-9) &&
      warm.length === 153 &&
      near(Math.min(...warm.map((e) => e.lo)), -19.1, 1e-9) &&
      WHITE_BIN.lo === -92.1 &&
      COLOUR_BINS.length === 74,
    `cold grey ramp ${cold.length} bins (${Math.min(...cold.map((e) => e.lo))} to ` +
      `${Math.max(...cold.map((e) => e.hi))} C, levels ${cold[0].r}..${cold[cold.length - 1].r}), ` +
      `warm grey ramp ${warm.length} bins from ${Math.min(...warm.map((e) => e.lo))} C ` +
      `(levels ${warm[0].r}..${warm[warm.length - 1].r}), white the ${WHITE_BIN.lo} C bin, ` +
      `${COLOUR_BINS.length} colour bins between - the two grey ramps share levels, hence the rule`
  );
  // the grey tolerance sits under half the palette's least colour
  // saturation, and the white split between the cold ramp's top
  // level and white itself (144th sweep: derived, not typed)
  const minSat = Math.min(
    ...COLOUR_BINS.map((e) => Math.max(e.r, e.g, e.b) - Math.min(e.r, e.g, e.b))
  );
  const coldTop = Math.max(...COLD_GREYS.map((e) => e.r));
  check(
    "THE GREY TOLERANCE and the white split are the palette's own",
    GREY_SAT_MAX * 2 < minSat &&
      WHITE_SPLIT_LEVEL === (coldTop + WHITE_BIN.r) / 2 &&
      coldTop < WHITE_SPLIT_LEVEL &&
      WHITE_SPLIT_LEVEL < WHITE_BIN.r,
    `a pixel is grey under a saturation of ${GREY_SAT_MAX}; the palette's least saturated ` +
      `colour is ${minSat} levels from grey; white is read above level ${WHITE_SPLIT_LEVEL}, ` +
      `halfway between the cold ramp's top level ${coldTop} and white ${WHITE_BIN.r}`
  );
  // every bin's own colour decodes to its own reading
  let round = 0;
  for (const e of B13_BINS) {
    let t;
    if (!e.grey) t = colourReading(e.r, e.g, e.b);
    else if (e.r >= 240) t = WHITE_BIN.tC;
    else if (e.tC < -60) t = greyReading(COLD_GREYS, e.r);
    else t = greyReading(WARM_GREYS, e.r);
    if (near(t, e.tC, 1e-9)) round++;
  }
  check(
    'EVERY BIN reads back as itself on its own ramp',
    round === B13_BINS.length,
    `${round} of ${B13_BINS.length} bins decode to their own midpoint (colour by nearest ` +
      `entry, greys on the ramp their region selects)`
  );
}

// ---- the grey rule on a synthetic anvil -----------------------
{
  const W = 40;
  const rgba = new Uint8Array(W * W * 4);
  const put = (i, j, r, g, b) => {
    const k = (j * W + i) * 4;
    rgba[k] = r;
    rgba[k + 1] = g;
    rgba[k + 2] = b;
    rgba[k + 3] = 255;
  };
  const coldColour = COLOUR_BINS.find((e) => e.tC < -64 && e.tC > -66);
  const coldGrey = COLD_GREYS.find((e) => e.r === 102); // -74.6 C
  for (let j = 0; j < W; j++)
    for (let i = 0; i < W; i++) put(i, j, 120, 120, 120); // warm continent
  for (let j = 10; j < 19; j++)
    for (let i = 10; i < 19; i++)
      put(i, j, coldColour.r, coldColour.g, coldColour.b);
  for (let j = 12; j < 17; j++)
    for (let i = 12; i < 17; i++) put(i, j, 102, 102, 102); // the core
  put(30, 30, 102, 102, 102); // the resampler's stray grey inside the continent
  const dec = decodeTile(rgba, W, W);
  const census = resolveGreys(dec);
  const core = dec.bt[14 * W + 14];
  const stray = dec.bt[30 * W + 30];
  const continent = dec.bt[3 * W + 3];
  check(
    'THE GREY RULE resolves an enclosed core cold and leaves the continent warm',
    census.coldPixels === 25 &&
      census.coldRegions === 1 &&
      near(core, coldGrey.tC, 1e-4) &&
      near(stray, greyReading(WARM_GREYS, 102), 1e-4) &&
      near(continent, greyReading(WARM_GREYS, 120), 1e-4),
    `a 5x5 grey core ringed by ${coldColour.tC} C colour reads ${core.toFixed(1)} C ` +
      `(${census.coldPixels} px on the cold ramp, ${census.coldRegions} region); the same ` +
      `grey level alone in the continent reads ${stray.toFixed(1)} C and the continent ` +
      `${continent.toFixed(1)} C although its ONLY colour border is that same cold ring - ` +
      `the ring encloses the core, not the continent; no flood (a continuity rule floods ` +
      `258,634 of 258,636 greys on the real tiles)`
  );
}

// ---- Planck and the code's radiation constant -----------------
{
  const rt = [200, 250, 300].every((T) => near(planckT(planckB(T)), T, 1e-9));
  const xkt = 290 / RADCN2_CM_K;
  const nu = 966.18;
  const tanhForm = nu * Math.tanh(nu / (2 * xkt));
  check(
    "PLANCK round-trips and RADFN is nu tanh(nu / 2 XKT) on the code's RADCN2",
    rt &&
      near(RADCN2_CM_K, 1.4387752, 3e-6) &&
      near(radfn(nu, 290), tanhForm, 1e-9),
    `planckT(planckB(T)) = T at 200/250/300 K; the theme's SI constants give RADCN2 ` +
      `${RADCN2_CM_K.toFixed(7)} cm K against phys_consts.f90's 1.4387752; radfn(966.18, 290 K) = ` +
      `${radfn(nu, 290).toFixed(3)} cm^-1 = the closed form`
  );
}

// ---- the MT_CKD slice -----------------------------------------
{
  const s = MT_CKD_WINDOW.self296;
  let falling = true;
  for (let i = 1; i < s.length; i++) if (!(s[i] < s[i - 1])) falling = false;
  const c = mtCkdAt(966.18);
  const L = {pPa: 98000, tK: 290, ePa: 1800, dzM: 800};
  const t1 = layerContinuumTau(L);
  const t2 = layerContinuumTau({...L, ePa: 3600});
  check(
    'THE CLEAN WINDOW: self continuum falls across band 13, foreign is a thousandth, self goes as e^2',
    falling &&
      c.foreign / c.self296 < 1e-3 &&
      c.selfExp > 5.77 &&
      c.selfExp < 5.92 &&
      near(foreignScale(966.18), 1.0059, 5e-4) &&
      near(t2.self / t1.self, 4, 1e-9) &&
      near(
        t2.foreign / t1.foreign,
        (2 * (1 - 3600 / 98000)) / (1 - 1800 / 98000),
        1e-9
      ),
    `S296 ${s[0]} -> ${s[s.length - 1]} (x1e-20 cm^3/molecule) from 940 to 1000 cm^-1; at 966.18 ` +
      `self ${c.self296.toExponential(3)}, exponent ${c.selfExp.toFixed(3)}, foreign/self ` +
      `${(c.foreign / c.self296).toExponential(2)}, FSCAL ${foreignScale(966.18).toFixed(5)}; doubling ` +
      `the vapour quadruples the self term (${(t2.self / t1.self).toFixed(6)}) - a moist 800-m layer at ` +
      `18 hPa is tau ${t1.tau.toFixed(4)}`
  );
}

// ---- the sea's emissivity -------------------------------------
{
  const {n, k} = WATER_INDEX_B13;
  const r0 = ((n - 1) ** 2 + k * k) / ((n + 1) ** 2 + k * k);
  const f0 = fresnelReflectance(0);
  const e44 = seaEmissivity(44);
  const angles = [0, 20, 40, 50, 60, 70, 80];
  let falling = true;
  for (let i = 1; i < angles.length; i++)
    if (!(seaEmissivity(angles[i]) < seaEmissivity(angles[i - 1])))
      falling = false;
  const brewster = Math.atan(n) / (Math.PI / 180);
  check(
    "THE SEA'S EMISSIVITY is Fresnel on Hale & Querry's index",
    near(f0.r, r0, 1e-12) &&
      near(f0.rs, f0.rp, 1e-12) &&
      e44 > 0.985 &&
      e44 < 0.99 &&
      falling &&
      fresnelReflectance(brewster).rp < 1e-3,
    `n = ${n.toFixed(4)}, k = ${k.toFixed(4)} at 10.35 um; nadir reflectance ${f0.r.toFixed(5)} = ` +
      `((n-1)^2+k^2)/((n+1)^2+k^2) with Rs = Rp; emissivity ${seaEmissivity(0).toFixed(4)} at nadir, ` +
      `${e44.toFixed(4)} at 44 deg, falling with angle; Rp ${fresnelReflectance(brewster).rp.toExponential(1)} ` +
      `at Brewster's ${brewster.toFixed(1)} deg`
  );
}

